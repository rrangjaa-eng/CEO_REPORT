def write(folder, name, rows, header=None):
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, name), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header or SCHEMA[name])
        for r in rows:
            w.writerow(r)


