def _won(v):
    return "-" if v is None else "{:,}".format(int(v))


def measured_now(track):
    """자동 분석 15 기록으로 이번에 잰 값 -> {'week': 글 또는 None, 'profit': 글 또는 None}."""
    out = {"week": None, "profit": None}
    K = track or {}
    gaps = []
    for r in K.get("weeks") or []:
        if r.get("part"):
            continue
        for io in ("in", "out"):
            c = r.get(io) or {}
            if c.get("all") is not None and c.get("actual") is not None:
                gaps.append(abs(c["actual"] - c["all"]))
    if gaps:
        gaps.sort()
        out["week"] = "그 뒤 4주 입·출금 %d번: 가운데 %s원 · 가장 큰 %s원" % (len(gaps), _won(gaps[len(gaps) // 2]), _won(gaps[-1]))
    pg = [abs(p["actual"] - p["forecast"]) for p in K.get("profit") or [] if p.get("actual") is not None and p.get("forecast") is not None]
    if pg:
        pg.sort()
        out["profit"] = "%d번: 가운데 %s원 · 가장 큰 %s원" % (len(pg), _won(pg[len(pg) // 2]), _won(pg[-1]))
    return out


